#!/bin/sh
# Builds a rescue boot area in rescue/BOARD/boot.bin with M-Flasher's own code
# (a scratch copy of its source with tools/rescuegen.rs hooked into main.rs),
# and writes src/rescue_info.h with the sizes and CRC32s of every board's.
# Only the boot area is kept: the rescue installs no firmware.
#
#   tools/make_rescue_image.sh BOARD M-FLASHER-SRC OFFICIAL.fwsc
#
# BOARD           fm1 or smk37
# M-FLASHER-SRC   checkout of github.com/jvitkauskas/m-flasher (its data/ has
#                 m-bootloader's bootloader-BOARD.boot)
# OFFICIAL.fwsc   an official M-VAVE package for the board (FM-1 015, SMK-37
#                 Pro 016): the boot area's flash header, file table and
#                 chip-key record come from it (its app only lets rescuegen
#                 check the whole image; it is not kept)
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
board=$1; src=$2; base=$3; fw=$3
case $board in fm1|smk37) ;; *) echo "BOARD: fm1 or smk37" >&2; exit 1 ;; esac
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
rsync -a --exclude target --exclude .git "$src/" "$work/mflasher/"
cp "$here/tools/rescuegen.rs" "$work/mflasher/src/rescuegen.rs"
python3 - "$work/mflasher/src/main.rs" <<'PY'
import sys
p = sys.argv[1]; s = open(p).read()
s = s.replace('mod ops;\n', 'mod ops;\nmod rescuegen;\n', 1)
s = s.replace('    let args: Vec<String> = std::env::args().skip(1).collect();\n',
              '    let args: Vec<String> = std::env::args().skip(1).collect();\n'
              '    if args.first().map(String::as_str) == Some("rescue-image") {\n'
              '        std::process::exit(rescuegen::run(&args[1..]));\n    }\n', 1)
open(p, 'w').write(s)
PY
(cd "$work/mflasher" && CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$work/target}" cargo build --release -q)
RESCUE_BOOT_BASE="$base" "${CARGO_TARGET_DIR:-$work/target}/release/m-flasher" rescue-image \
    "$fw" "$src/data/bootloader-$board.boot" "$work/out"
mkdir -p "$here/rescue/$board"
cp "$work/out/boot.bin" "$here/rescue/$board/"
python3 - "$here" <<'PY'
import sys, zlib, hashlib, os
here = sys.argv[1]
out = ['// Generated by tools/make_rescue_image.sh: the rescue boot areas in',
       '// rescue/BOARD/, embedded by src/rescue_blob.S.', '#pragma once', '#include <stdint.h>', '']
for board in ('fm1', 'smk37'):
    if not os.path.exists(f'{here}/rescue/{board}/boot.bin'):
        continue
    b = open(f'{here}/rescue/{board}/boot.bin', 'rb').read()
    assert len(b) == 0x4000
    B = board.upper()
    out += [f'#define RESCUE_HAVE_{B} 1',
            f'static const uint32_t RESCUE_{B}_BOOT_LEN = {len(b)};',
            f'static const uint32_t RESCUE_{B}_BOOT_CRC32 = 0x{zlib.crc32(b):08X};',
            f'// sha256 {board} boot {hashlib.sha256(b).hexdigest()}', '']
open(f'{here}/src/rescue_info.h', 'w').write('\n'.join(out))
print('\n'.join(out))
PY
