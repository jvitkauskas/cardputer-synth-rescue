#!/usr/bin/env python3
"""The guided mode's fonts: DejaVu Sans (Bitstream Vera licence, DejaVu's
changes public domain: permissive) rendered at the sizes the pages need, in
Adafruit GFX's 1-bit format that M5GFX draws, as src/ui_fonts.h.

    tools/make_fonts.py [DEJAVU_TTF_DIR]   (default /usr/share/fonts/truetype/dejavu)
"""
import pathlib, sys
from PIL import Image, ImageDraw, ImageFont

here = pathlib.Path(__file__).resolve().parent.parent
ttf_dir = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu')
FONTS = [  # C name, file, pixel size
    ('UiTitle', 'DejaVuSans-Bold.ttf', 16),
    ('UiBody', 'DejaVuSans.ttf', 14),
]
FIRST, LAST = 0x20, 0x7E


def gfx_font(name, path, size):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    bits, glyphs = bytearray(), []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')  # relative to the baseline
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(bits)
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
            acc = nb = 0
            for y in range(h):
                for x in range(w):
                    acc = (acc << 1) | (im.getpixel((x, y)) >= 128)
                    nb += 1
                    if nb == 8:
                        bits.append(acc)
                        acc = nb = 0
            if nb:
                bits.append(acc << (8 - nb))
        else:
            w = h = 0
        glyphs.append((offset, w, h, adv, x0, y0, ch))
    out = [f'// {name}: {path.name} at {size} px (generated by tools/make_fonts.py)',
           f'static const uint8_t {name}Bitmaps[] = {{']
    for i in range(0, len(bits), 16):
        out.append('    ' + ', '.join(f'0x{b:02X}' for b in bits[i:i + 16]) + ',')
    out += ['};', f'static const lgfx::GFXglyph {name}Glyphs[] = {{']
    for off, w, h, adv, xo, yo, ch in glyphs:
        out.append(f'    {{{off:5}, {w:3}, {h:3}, {adv:3}, {xo:3}, {yo:4}}},  // 0x{ord(ch):02X} {ch!r}')
    out += ['};', f'static const lgfx::GFXfont {name}((uint8_t *){name}Bitmaps, (lgfx::GFXglyph *){name}Glyphs, '
                  f'0x{FIRST:02X}, 0x{LAST:02X}, {ascent + descent});', '']
    return out, len(bits)


lines = ['// Generated by tools/make_fonts.py: the guided mode\'s fonts, from DejaVu Sans',
         '// (https://dejavu-fonts.github.io/, Bitstream Vera licence; DejaVu changes public domain).',
         '#pragma once', '#include <M5GFX.h>', '']
for name, file, size in FONTS:
    out, n = gfx_font(name, ttf_dir / file, size)
    lines += out
    print(f'{name}: {file} {size} px, {n} bytes of bitmaps')
(here / 'src' / 'ui_fonts.h').write_text('\n'.join(lines))
