#!/usr/bin/env python3
"""The guided mode's pictures: art/generated/NAME.png (large, any size) become
art/NAME.png (100x100, a 32-colour palette, on black), embedded by the
generated src/art_blob.S and listed in src/art_table.cpp."""
import pathlib
from PIL import Image

here = pathlib.Path(__file__).resolve().parent.parent
src, out = here / 'art' / 'generated', here / 'art'
SIZE = 100
names = []
for f in sorted(src.glob('*.png')) if src.exists() else []:
    im = Image.open(f).convert('RGB')
    w, h = im.size
    s = min(w, h)  # centre square
    im = im.crop(((w - s) // 2, (h - s) // 2, (w - s) // 2 + s, (h - s) // 2 + s))
    im = im.resize((SIZE, SIZE), Image.LANCZOS)
    im = im.quantize(colors=32, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    dst = out / f.name
    im.save(dst, optimize=True)
    names.append(f.stem)
    print(f'{f.name:16} {dst.stat().st_size:6} bytes')

asm = ['/* Generated by tools/make_art.py: the guided mode\'s pictures. */',
       '    .section .rodata.art, "a"']
for n in names:
    asm += ['    .balign 4', f'    .global art_{n}', f'art_{n}:', f'    .incbin "art/{n}.png"',
            f'    .global art_{n}_end', f'art_{n}_end:']
(here / 'src' / 'art_blob.S').write_text('\n'.join(asm) + '\n')

cpp = ['// Generated by tools/make_art.py: the guided mode\'s pictures.', '#include "art.h"', '',
       'extern "C" const uint8_t ' + ', '.join(f'art_{n}[], art_{n}_end[]' for n in names) + ';' if names else '',
       '', 'namespace art {', 'const Entry TABLE[] = {']
cpp += [f'    {{"{n}", art_{n}, (uint32_t)(art_{n}_end - art_{n})}},' for n in names]
if not names:
    cpp.append('    {"", nullptr, 0},')
cpp += ['};', f'const int COUNT = {len(names)};', '}  // namespace art', '']
(here / 'src' / 'art_table.cpp').write_text('\n'.join(cpp))
print(f'{len(names)} pictures')
